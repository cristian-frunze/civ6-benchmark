"""Build one HTML page for the hotseat games (several Opus seats and built-in AI civs on one map): each civ's score turn
by turn, the cost of each seat, and the standings.

    python3 tools/report_hotseat.py --out ~/tailscale-share/civ6-results/hotseat.html \
        [--game h1-four-opus] [--game h1-four-opus=~/.civ6-bench/runs/h1-four-opus] ...

Each --game is a results/<id>/ folder or, with =<dir>, a live run directory (both hold rounds.jsonl and turns.jsonl).
Without --game it uses every results/ folder that has a rounds.jsonl. Same style as tools/report.py's page.
"""

import argparse
import html
import json
import statistics
from pathlib import Path

import report

REPO = Path(__file__).resolve().parent.parent
STYLE = report.PAGE[report.PAGE.index("<style>"):report.PAGE.index("</style>") + len("</style>")]


def _rows(p: Path) -> list[dict]:
    return [json.loads(ln) for ln in open(p) if ln.strip()] if p.exists() else []


def load(gid: str, src: Path) -> dict:
    rounds, turns = _rows(src / "rounds.jsonl"), _rows(src / "turns.jsonl")
    meta = json.loads((src / "game.json").read_text()) if (src / "game.json").exists() else {}
    readme = src / "README.md"
    title, result = meta.get("title") or gid, "in progress"
    if readme.exists():
        text = readme.read_text()
        title = text.splitlines()[0].lstrip("# ").strip() or title
        hit = report.re.search(r"\*\*Result: ([^*]+?)\.?\*\*", text)
        result = hit.group(1) if hit else "finished"
    models = {a.get("slot"): a.get("model") for a in meta.get("agents", [])}
    seat_of = {a["slot"]: a["name"] for a in meta.get("agents", []) if "slot" in a}
    for t in turns:
        seat_of.setdefault(t["slot"], t["seat"])
    seats = []
    for slot, seat in sorted(seat_of.items()):
        xs = [t for t in turns if t["seat"] == seat]
        seats.append({"seat": seat, "slot": slot, "model": models.get(slot) or "", "turns": len({t["turn"] for t in xs}),
                      "usd": round(sum(t.get("usd") or 0 for t in xs), 2),
                      "median_s": round(statistics.median(t["seconds"] for t in xs)) if xs else 0,
                      "retries": sum(1 for t in xs if t.get("try", 1) > 1)})
    civs: dict[int, dict] = {}
    for r in rounds:
        for p in r["players"]:
            c = civs.setdefault(p["id"], {"id": p["id"], "civ": p["civ"], "seat": seat_of.get(p["id"]), "score": []})
            c["score"].append([r["turn"], p["score"]])
    last = rounds[-1] if rounds else {"players": [], "turn": 0}
    standings = sorted(({"civ": p["civ"], "seat": seat_of.get(p["id"]), "alive": p.get("alive", True),
                         "score": p["score"], "cities": p["cities"], "science": round(p["science"]),
                         "techs": p["techs"], "civics": p["civics"], "military": p["military"]}
                        for p in last["players"]), key=lambda r: -r["score"])
    usd = sum(t.get("usd") or 0 for t in turns)
    wall = (max(t["end"] for t in turns) - min(t["start"] for t in turns)) / 3600 if turns else 0
    opus = [s["score"] for s in standings if s["seat"]]
    ai = [s["score"] for s in standings if not s["seat"]]
    return {"id": gid, "title": title, "result": result, "turn": last.get("turn", 0), "usd": round(usd, 2),
            "wall_h": round(wall, 1), "seats": seats, "civs": [civs[k] for k in sorted(civs)], "standings": standings,
            "opus_avg": round(statistics.mean(opus)) if opus else None, "ai_avg": round(statistics.mean(ai)) if ai else None}


